/**
 * mergeChunks.mjs — roll every delivered chunk file into the 42 batchNN.mjs modules
 * that index.mjs already imports.
 *
 * Sources, in precedence order (later wins):
 *   1. the existing batchNN.mjs files (preserves work done before chunking)
 *   2. _chunks/<chunkId>.mjs written by research subagents
 *
 * Exams are re-filed into the batch their slug belongs to according to
 * _input/batchNN.json, so a chunk that strays across batches still lands correctly.
 *
 *   node mergeChunks.mjs          # merge + write
 *   node mergeChunks.mjs --dry    # report only
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const INPUT = path.join(HERE, '_input');
const CHUNKS = path.join(HERE, '_chunks');
const dry = process.argv.includes('--dry');

/* ── slug → batch map ─────────────────────────────────────────── */
const slugBatch = new Map();
for (let n = 1; n <= 42; n += 1) {
  const f = path.join(INPUT, `batch${String(n).padStart(2, '0')}.json`);
  if (!fs.existsSync(f)) continue;
  for (const e of JSON.parse(fs.readFileSync(f, 'utf8')).exams || []) slugBatch.set(e.slug, n);
}

/* ── collect ──────────────────────────────────────────────────── */
const programs = new Map(); // id → program
const exams = new Map(); // slug → exam
const problems = [];

async function absorb(file, label) {
  try {
    const mod = await import(`${pathToFileURL(file).href}?t=${Date.now()}`);
    const p = mod.programs || mod.default?.programs || [];
    const e = mod.exams || mod.default?.exams || [];
    for (const prog of p) if (prog?.id) programs.set(prog.id, prog);
    for (const ex of e) if (ex?.slug) exams.set(ex.slug, ex);
    return { p: p.length, e: e.length };
  } catch (err) {
    problems.push(`${label}: ${err.message.split('\n')[0]}`);
    return null;
  }
}

// 1. existing batch modules
for (let n = 1; n <= 42; n += 1) {
  const f = path.join(HERE, `batch${String(n).padStart(2, '0')}.mjs`);
  if (fs.existsSync(f)) await absorb(f, `batch${n}`);
}
const baseExams = exams.size;
const basePrograms = programs.size;

// 2. chunk modules (override)
let chunkFiles = [];
if (fs.existsSync(CHUNKS)) {
  chunkFiles = fs.readdirSync(CHUNKS).filter((f) => f.endsWith('.mjs')).sort();
  for (const f of chunkFiles) await absorb(path.join(CHUNKS, f), f);
}

/* ── serialise ────────────────────────────────────────────────── */
function ser(v, ind = 0) {
  const pad = '  '.repeat(ind);
  const pad2 = '  '.repeat(ind + 1);
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
  if (Array.isArray(v)) {
    if (v.length === 0) return '[]';
    const scalars = v.every((x) => typeof x !== 'object' || x === null);
    if (scalars && v.join('').length < 70) return `[${v.map((x) => ser(x)).join(', ')}]`;
    return `[\n${v.map((x) => pad2 + ser(x, ind + 1)).join(',\n')}\n${pad}]`;
  }
  const keys = Object.keys(v).filter((k) => v[k] !== undefined);
  if (keys.length === 0) return '{}';
  return `{\n${keys.map((k) => `${pad2}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`}: ${ser(v[k], ind + 1)}`).join(',\n')}\n${pad}}`;
}

function render(id, progs, exs) {
  return `// AUTO-GENERATED by mergeChunks.mjs — edit the chunk sources, not this file.
// batch ${id}: ${progs.length} program dossier(s), ${exs.length} exam record(s).

export const programs = ${ser(progs, 0)};

export const exams = ${ser(exs, 0)};

export default { programs, exams };
`;
}

/* ── redistribute into batches ────────────────────────────────── */
const perBatchExams = new Map();
let orphans = 0;
for (const [slug, ex] of exams) {
  const n = slugBatch.get(slug);
  if (!n) {
    orphans += 1;
    continue;
  }
  if (!perBatchExams.has(n)) perBatchExams.set(n, []);
  perBatchExams.get(n).push(ex);
}

// Two chunks can each mint a dossier for the same certifying body under different
// ids (e.g. 'ets' and 'ets-org'). index.mjs keys programs by body, so a duplicate
// body is a hard error — collapse them here, keeping the richer dossier.
const weigh = (p) =>
  JSON.stringify(p).length + (p.registrationSteps?.length || 0) * 500 + (p.comparison ? 800 : 0);
const bodyToProgram = new Map();
let collapsed = 0;
for (const p of programs.values()) {
  if (!p.body) continue;
  const prev = bodyToProgram.get(p.body);
  if (!prev) bodyToProgram.set(p.body, p);
  else {
    collapsed += 1;
    if (weigh(p) > weigh(prev)) bodyToProgram.set(p.body, p);
  }
}

// index.mjs pools every batch into one registry, so each dossier must be emitted
// exactly ONCE across all 42 files — a body appearing twice is a validation error.
// It lands in the lowest-numbered batch that actually uses it.
let written = 0;
const emitted = new Set();
const plan = [];
for (let n = 1; n <= 42; n += 1) {
  const exs = (perBatchExams.get(n) || []).sort((a, b) => a.slug.localeCompare(b.slug));
  const bodies = [...new Set(exs.map((e) => e.body).filter(Boolean))];
  const progs = [];
  for (const b of bodies) {
    if (emitted.has(b)) continue;
    const p = bodyToProgram.get(b);
    if (!p) continue;
    emitted.add(b);
    progs.push(p);
  }
  plan.push({ n, exs, progs });
}

// Any dossier whose body has no exam yet would otherwise be silently lost on the
// next rewrite. Park them in batch01 so the research survives.
const orphanPrograms = [...bodyToProgram.values()].filter((p) => !emitted.has(p.body));
if (orphanPrograms.length) plan[0].progs.push(...orphanPrograms);

for (const { n, exs, progs } of plan) {
  const id = String(n).padStart(2, '0');
  const uniq = [...new Map(progs.map((p) => [p.body, p])).values()].sort((a, b) => a.id.localeCompare(b.id));
  const out = render(id, uniq, exs);
  const file = path.join(HERE, `batch${id}.mjs`);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (prev !== out) {
    if (!dry) fs.writeFileSync(file, out, 'utf8');
    written += 1;
  }
}

/* ── report ───────────────────────────────────────────────────── */
console.log(`chunk modules found : ${chunkFiles.length}`);
console.log(`programs            : ${bodyToProgram.size}  (base ${basePrograms}, ${collapsed} duplicate-body dossier(s) collapsed)`);
console.log(`exam records        : ${exams.size}  (base ${baseExams})`);
console.log(`batch files ${dry ? 'would change' : 'rewritten'} : ${written}`);
if (orphanPrograms.length) console.log(`  (${orphanPrograms.length} dossier(s) with no exam yet parked in batch01)`);
if (orphans) console.log(`! ${orphans} record(s) had a slug not present in any _input batch — dropped`);
if (problems.length) {
  console.log(`\n! ${problems.length} source(s) failed to parse:`);
  for (const p of problems) console.log(`  - ${p}`);
}
