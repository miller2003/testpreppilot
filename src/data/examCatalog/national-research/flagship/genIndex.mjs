/**
 * genIndex.mjs — regenerates flagship/index.mjs from the *.mjs files in this folder.
 *
 * The flagship layer is the highest-priority source for national records and
 * program dossiers: national-research/index.mjs puts it FIRST in the batch list
 * and the pooling logic keeps the first record per slug / first program per body.
 * Writers add one file per work package (pkgNN.mjs) exporting { programs, exams }
 * and never touch the batchNN.mjs files or mergeChunks.mjs.
 *
 *   node src/data/examCatalog/national-research/flagship/genIndex.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const files = fs
  .readdirSync(HERE)
  .filter((f) => f.endsWith('.mjs') && f !== 'index.mjs' && f !== 'genIndex.mjs')
  .sort();

const imports = files.map((f, i) => `import f${i} from './${f}';`).join('\n');
const list = files.map((_, i) => `f${i}`).join(', ');
const body = `// AUTO-GENERATED by genIndex.mjs — do not edit by hand.
${imports}

const FILES = [${list}];

export const programs = FILES.flatMap((f) => f?.programs || []);
export const exams = FILES.flatMap((f) => f?.exams || []);
export default { programs, exams };
`;
const out = path.join(HERE, 'index.mjs');
const tmp = `${out}.${process.pid}.tmp`;
fs.writeFileSync(tmp, body);
fs.renameSync(tmp, out);
console.log(`flagship index: ${files.length} file(s)`);
