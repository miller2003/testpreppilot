// Regenerates ./depth/index.mjs from every ./depth/<slug>.mjs file.
// Run: node src/data/examCatalog/_gen_depth_index.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const depthDir = join(here, 'depth');

const files = readdirSync(depthDir).filter(f => f.endsWith('.mjs') && f !== 'index.mjs');
files.sort();

const imports = files.map((f, i) => `import d${i} from './${f}';`).join('\n');
const keys = files.map((f, i) => {
  const slug = f.replace(/\.mjs$/, '');
  return `  ${JSON.stringify(slug)}: d${i}`;
}).join(',\n');

const out = `// AUTO-GENERATED by _gen_depth_index.mjs — do not edit by hand.
${imports}

const examDepth = {
${keys}
};

export default examDepth;
`;

writeFileSync(join(depthDir, 'index.mjs'), out);
console.log(`depth/index.mjs regenerated with ${files.length} entries.`);
