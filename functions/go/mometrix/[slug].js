// Cloudflare Pages Function: /go/mometrix/<slug> -> Mometrix affiliate link.
//
// Two lanes, and a bot never reaches the tracking link by simply fetching a URL:
//
//   Lane A (zero friction, the normal case)
//     A real click on an exam page makes MometrixPrep.astro stamp a short-lived
//     ticket cookie (mxg, 120s, Path=/go/) and then lets the browser navigate
//     natively. GET + fresh ticket + same-origin Referer + clean browser signals
//     -> 302 immediately. No interstitial, no extra round trip, no JS challenge.
//
//   Lane B (one extra click, the safety net)
//     Anything else that is not unambiguously automated -> a small branded
//     "Continue to Mometrix" page. Its button POSTs back here (Origin + Referer
//     same-origin) and only then gets the 302. Right-click "open in new tab",
//     copied links, disabled JS and disabled cookies all still work for humans;
//     a crawler that only fetches GET URLs never produces a Mometrix click.
//
//   Hard denies (403/204/405) are reserved for things no human click produces:
//     prefetch/prerender, HEAD/other methods, crawler or HTTP-library UAs,
//     Cloudflare verified bots, low Bot Management scores.
//
// Every decision is logged to PostHog server-side as `aff_outbound`
// (decision / reason / lane / CF fingerprints) via waitUntil, so the count of
// real redirects can be reconciled with the Mometrix panel and the rules tuned.
// Server events carry no $session_id, so they never inflate session traffic.
//
// Product table: src/data/mometrix.mjs (generated by scripts/mometrix/build.mjs).
