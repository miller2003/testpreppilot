// Cloudflare Pages Function: /go/mometrix/<slug> -> Mometrix affiliate link.
//
// Real visitors get a 302 to the ref.mometrix.com tracking link. Anything that
// is not a person clicking a link is turned away BEFORE the tracking link is
// revealed, so it never reaches Mometrix's click log:
//   · prefetch / prerender requests (Astro's hover prefetch, browser speculation) -> 204
//   · HEAD and other non-GET methods (link checkers)                             -> 405
//   · crawlers, link-preview fetchers, HTTP libraries, headless browsers          -> 403
// Every response is noindex and uncacheable. robots.txt also disallows /go/.
//
// Product table: src/data/mometrix.mjs (generated by scripts/mometrix/build.mjs).
import { mometrixProducts } from '../../../src/data/mometrix.mjs';

const TARGETS = new Map(Object.values(mometrixProducts).map((p) => [p.goSlug, p.href]));
const REF_LINK = /^https:\/\/ref\.mometrix\.com\/1262-\d+-\d+-\d+\.htm$/;

// Substrings that never appear in a mainstream browser's User-Agent.
const AUTOMATED_UA = new RegExp(
  [
    'bot\\b', 'bot/', 'crawl', 'spider', 'slurp', 'archiver', 'scraper', 'fetcher', 'preview', 'validator',
    'checker', 'monitor', 'headless', 'phantomjs', 'puppeteer', 'playwright', 'selenium', 'webdriver',
    'lighthouse', 'pagespeed', 'gtmetrix', 'pingdom', 'uptime', 'curl', 'wget', 'python', 'httpx', 'aiohttp',
    'axios', 'node-fetch', 'undici', 'go-http', 'okhttp', 'java/', 'libwww', 'httpclient', 'postman', 'insomnia',
    'facebookexternalhit', 'facebookcatalog', 'meta-external', 'whatsapp', 'telegram', 'slack', 'discord',
    'skypeuripreview', 'embedly', 'pinterest', 'vkshare', 'redditbot', 'mediapartners', 'adsbot', 'google-',
    'feedfetcher', 'yandex', 'baidu', 'duckduck', 'petal', 'semrush', 'ahrefs', 'mj12', 'dotbot', 'bytespider',
    'gptbot', 'chatgpt', 'oai-search', 'claude', 'anthropic', 'perplexity', 'ccbot', 'amazonbot', 'applebot',
    'cohere', 'diffbot', 'youbot', 'bingpreview'
  ].join('|'),
  'i'
);

const BASE_HEADERS = {
  'Cache-Control': 'private, no-store, max-age=0',
  'X-Robots-Tag': 'noindex, nofollow, noarchive',
  'Referrer-Policy': 'strict-origin-when-cross-origin'
};

function page(status, title, body) {
  return new Response(
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex,nofollow">` +
      `<meta name="viewport" content="width=device-width,initial-scale=1"><title>${title}</title></head>` +
      `<body style="font-family:Georgia,serif;max-width:36rem;margin:4rem auto;padding:0 1rem;line-height:1.6">` +
      `<h1 style="font-size:1.4rem">${title}</h1><p>${body}</p><p><a href="/">Back to TestPrepPilot</a></p></body></html>`,
    { status, headers: { ...BASE_HEADERS, 'Content-Type': 'text/html; charset=utf-8' } }
  );
}

/** Why this request must not be redirected, or null for a real visitor. */
function automationReason(request) {
  const h = request.headers;
  const purpose = `${h.get('sec-purpose') || ''} ${h.get('purpose') || ''} ${h.get('x-purpose') || ''} ${h.get('x-moz') || ''}`.toLowerCase();
  if (/prefetch|prerender|preview/.test(purpose)) return 'prefetch';

  const ua = h.get('user-agent') || '';
  if (ua.length < 25 || !/mozilla\/5\.0/i.test(ua) || AUTOMATED_UA.test(ua)) return 'user-agent';

  const cf = request.cf || {};
  if (cf.verifiedBotCategory || cf.botManagement?.verifiedBot) return 'verified-bot';
  const score = cf.botManagement?.score;
  if (typeof score === 'number' && score > 0 && score < 30) return 'bot-score';

  // Fetch Metadata: opening a link sends mode=navigate, dest=document. fetch(),
  // <img>, <iframe> and similar background loads send something else. Browsers
  // too old to send these headers are judged on the user-agent checks above.
  // (Sec-Fetch-User is deliberately not required: some in-app browsers omit it
  // on real taps, and those clicks would lose their commission.)
  const mode = h.get('sec-fetch-mode');
  if (mode !== null && mode !== 'navigate') return 'fetch-mode';
  const dest = h.get('sec-fetch-dest');
  if (dest !== null && dest !== 'document') return 'fetch-dest';
  return null;
}

export async function onRequest({ request, params }) {
  const slug = String(Array.isArray(params.slug) ? params.slug[0] : params.slug || '').toLowerCase();
  const target = TARGETS.get(slug);
  if (!target || !REF_LINK.test(target)) {
    return page(404, 'Link not found', 'This outbound link does not exist or has been retired.');
  }

  if (request.method !== 'GET') {
    return new Response(null, { status: 405, headers: { ...BASE_HEADERS, Allow: 'GET' } });
  }

  const reason = automationReason(request);
  if (reason === 'prefetch') return new Response(null, { status: 204, headers: BASE_HEADERS });
  if (reason) {
    return page(403, 'Outbound affiliate link', 'This link forwards visitors to a partner site and is not available to automated clients.');
  }

  return new Response(null, { status: 302, headers: { ...BASE_HEADERS, Location: target } });
}
