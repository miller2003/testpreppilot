const ORIGINS = new Set(['https://testpreppilot.com', 'https://www.testpreppilot.com']);
const TICKET_TTL = 120; // seconds; matches Max-Age set by MometrixPrep.astro
const SUSPICION_LIMIT = 2;

const POSTHOG_KEY = 'phc_wKtYrkAQ9gynGBsKNW6bZ2PahhYaACwdXTtLSmhB8TCj';
const POSTHOG_CAPTURE = 'https://us.i.posthog.com/capture/';

