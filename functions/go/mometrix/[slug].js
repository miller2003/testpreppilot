/** Reasons no genuine click can produce, or null. */
function hardDenyReason(request) {
  const h = request.headers;
  const ua = h.get('user-agent') || '';
  if (ua.length < 25 || !/mozilla\/5\.0/i.test(ua) || AUTOMATED_UA.test(ua)) return 'user-agent';
  const cf = request.cf || {};
  if (cf.verifiedBotCategory || cf.botManagement?.verifiedBot) return 'verified-bot';
  const score = cf.botManagement?.score;
  if (typeof score === 'number' && score > 0 && score < 30) return 'bot-score';
  return null;
}

/**
 * Soft signals, scored. 0-1 -> Lane A (straight through), >=2 -> Lane B.
 * Nothing here can lock a human out: worst case is one extra tap.
 */
function suspicion(request) {
  const h = request.headers;
  const cf = request.cf || {};
  const ua = h.get('user-agent') || '';
  const flags = [];
  let score = 0;
  const add = (n, flag) => { score += n; flags.push(flag); };

  const chromeUa = /Chrome\/\d/.test(ua) && !/CriOS|EdgA|; wv/i.test(ua);
  const chPlatform = h.get('sec-ch-ua-platform');
  if (chromeUa && !h.get('sec-ch-ua')) add(2, 'no-client-hints');

  if (chPlatform) {
    const p = chPlatform.toLowerCase();
    const os = /windows/i.test(ua) ? 'windows'
      : /android/i.test(ua) ? 'android'
      : /mac os x|macintosh/i.test(ua) ? 'macos'
      : /iphone|ipad/i.test(ua) ? 'ios'
      : /linux/i.test(ua) ? 'linux' : null;
    const map = { windows: '"windows"', android: '"android"', macos: '"macos"', ios: '"ios"', linux: '"linux"' };
    if (os && map[os] && p !== map[os]) add(2, 'platform-mismatch');
  }

  if (/X11; Linux|Linux x86_64|Linux aarch64/i.test(ua) && !/android/i.test(ua)) add(1, 'linux-desktop');
  if (!h.get('accept-language')) add(1, 'no-lang');
  const accept = h.get('accept') || '';
  if (accept && !accept.includes('text/html')) add(1, 'accept');
  const site = h.get('sec-fetch-site');
  if (site && site !== 'same-origin') add(2, 'fetch-site');
  const threat = cf.threatScore;
  if (typeof threat === 'number' && threat >= 10) add(1, 'threat');
  if (HOSTING_ASNS.has(cf.asn)) add(1, 'hosting-asn');

  return { score, flags };
}

/** 'fresh' | 'missing' | 'stale' | 'future' for the mxg ticket cookie. */
function ticketState(cookieHeader) {
  const m = /(?:^|;\s*)mxg=(\d{9,11})\.([a-f0-9]{6,32})/i.exec(cookieHeader || '');
  if (!m) return 'missing';
  const ts = Number(m[1]);
  const now = Math.floor(Date.now() / 1000);
  if (ts - now > 30) return 'future';
  if (now - ts > TICKET_TTL) return 'stale';
  return 'fresh';
}

function sameOrigin(url) {
  try { return ORIGINS.has(new URL(url).origin); } catch { return false; }
}

function samePath(url, path) {
  try { return new URL(url).pathname === path; } catch { return false; }
}

/** Server-side analytics; never delays the redirect. */
function report(waitUntil, request, props) {
  if (!waitUntil) return;
  try {
    const cf = request.cf || {};
    const h = request.headers;
    const payload = {
      api_key: POSTHOG_KEY,
      event: 'aff_outbound',
      distinct_id: 'go_' + (cf.ray || crypto.randomUUID()),
      properties: {
        site: 'testpreppilot',
        $host: 'testpreppilot.com',
        $lib: 'cf-pages-function',
        $process_person_profile: false,
        $ip: h.get('cf-connecting-ip') || undefined,
        $geoip_country_code: cf.country || undefined,
        ua: (h.get('user-agent') || '').slice(0, 160),
        asn: cf.asn ?? null,
        bot_score: cf.botManagement?.score ?? null,
        threat_score: cf.threatScore ?? null,
        ch_platform: h.get('sec-ch-ua-platform'),
        ...props
      }
    };
    waitUntil(fetch(POSTHOG_CAPTURE, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    }).catch(() => {}));
  } catch { /* analytics must never break a redirect */ }
}

export async function onRequest({ request, params, waitUntil }) {
  const slug = String(Array.isArray(params.slug) ? params.slug[0] : params.slug || '').toLowerCase();
  const product = PRODUCTS.get(slug);
  const target = product?.href;
  if (!target || !REF_LINK.test(target)) {
    return page(404, 'Link not found', 'This outbound link does not exist or has been retired.');
  }

  const h = request.headers;
  const method = request.method;
  const path = new URL(request.url).pathname;
  const base = { slug, method, path };

  if (method !== 'GET' && method !== 'POST') {
    report(waitUntil, request, { ...base, decision: 'deny', reason: 'method' });
    return new Response(null, { status: 405, headers: { ...BASE_HEADERS, Allow: 'GET, POST' } });
  }

  const purpose = `${h.get('sec-purpose') || ''} ${h.get('purpose') || ''} ${h.get('x-purpose') || ''} ${h.get('x-moz') || ''}`.toLowerCase();
  if (/prefetch|prerender|preview/.test(purpose)) {
    report(waitUntil, request, { ...base, decision: 'deny', reason: 'prefetch' });
    return new Response(null, { status: 204, headers: BASE_HEADERS });
  }

  const hard = hardDenyReason(request);
  if (hard) {
    report(waitUntil, request, { ...base, decision: 'deny', reason: hard });
    return page(403, 'Outbound affiliate link',
      'This link forwards visitors to a partner site and is not available to automated clients.');
  }

  const referer = h.get('referer') || '';
  const origin = h.get('origin') || '';
  const mode = h.get('sec-fetch-mode');
  const dest = h.get('sec-fetch-dest');
  const badFetch = (mode !== null && mode !== 'navigate') || (dest !== null && dest !== 'document');

  if (method === 'POST') {
    // Lane B: the button on our own confirm page. Deliberately no soft scoring
    // here, so nobody (VPN, Linux, odd browser) can get stuck in a loop.
    const fromConfirm = ORIGINS.has(origin) && sameOrigin(referer) && samePath(referer, path) && !badFetch;
    const site = h.get('sec-fetch-site');
    if (fromConfirm && (!site || site === 'same-origin')) {
      report(waitUntil, request, { ...base, decision: 'redirect', lane: 'confirm-post' });
      return new Response(null, { status: 302, headers: { ...BASE_HEADERS, Location: target } });
    }
    report(waitUntil, request, { ...base, decision: 'deny', reason: 'post-origin' });
    return page(403, 'Outbound affiliate link', 'Please follow the link from its page on TestPrepPilot.');
  }

  // GET, Lane A.
  const ticket = ticketState(h.get('cookie'));
  const susp = suspicion(request);
  let decision = 'redirect';
  let reason = 'ok';
  if (ticket !== 'fresh') { decision = 'confirm'; reason = 'ticket-' + ticket; }
  else if (badFetch) { decision = 'confirm'; reason = 'fetch-metadata'; }
  else if (!sameOrigin(referer)) { decision = 'confirm'; reason = 'no-referer'; }
  else if (susp.score >= SUSPICION_LIMIT) { decision = 'confirm'; reason = susp.flags.join('+'); }

  report(waitUntil, request, {
    ...base, decision, reason,
    lane: decision === 'redirect' ? 'ticket' : null,
    suspicion: susp.score,
    flags: susp.flags.join(','),
    referer_path: sameOrigin(referer) ? new URL(referer).pathname : null
  });

  if (decision === 'redirect') {
    return new Response(null, { status: 302, headers: { ...BASE_HEADERS, Location: target } });
  }
  return confirmPage(product);
}
