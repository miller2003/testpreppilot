// Build src/data/mometrix.mjs from ads.json (the parsed affiliate export) and
// exam-map.mjs (the curated slug -> product mapping).
//
//   node scripts/mometrix/build.mjs
//
// Fails loudly on anything that could ship a wrong link: an unknown exam slug,
// a group name that is not in the export, or a link that is not a 1262 ref link.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import examMap, { notes } from './exam-map.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const ads = JSON.parse(fs.readFileSync(path.join(here, 'ads.json'), 'utf8'));
const { allExamsFull } = await import(pathToFileURL(path.join(root, 'src/data/examCatalog/index.mjs')).href);
const examBySlug = new Map(allExamsFull.map((e) => [e.slug, e]));

const LINK_RE = /^https:\/\/ref\.mometrix\.com\/1262-\d+-\d+-(\d+)\.htm$/;

// Cover images that answered 403 when fetched directly on 2026-10-19.
const BROKEN_IMAGES = new Set(['https://www.flashcardsecrets.com/civilservice/civilservice-cover_660.jpg']);

// Group names in the export carry typos and inconsistent suffixes.
const NAME_FIXES = {
  'ServSafe Manager Sercrets Study Guide': 'ServSafe Manager Secrets Study Guide',
  'NCLEX-PN Secrets': 'NCLEX-PN Secrets Study Guide',
  'PANCE Prep Review': 'PANCE Secrets Study Guide',
  'DAT Prep Book': 'DAT Secrets Study Guide',
  'CDA Exam Flashcards': 'DANB CDA Exam Flashcards'
};
const displayName = (group) => (NAME_FIXES[group] || group).replace(/ Online Study Course$/, ' Online Course');

const kindOf = (target) =>
  /flashcardsecrets\.com/.test(target) ? 'flashcards' : /mometrix\.com\/university\//.test(target) ? 'course' : 'guide';

const byGroup = new Map(ads.map((a) => [a.group, a]));
const errors = [];
const products = {};
const exams = {};

for (const [slug, groups] of Object.entries(examMap)) {
  const exam = examBySlug.get(slug);
  if (!exam) errors.push(`unknown exam slug: ${slug}`);
  const ids = [];
  for (const group of groups) {
    const ad = byGroup.get(group);
    if (!ad) { errors.push(`${slug}: group not in export: "${group}"`); continue; }
    const m = ad.link.match(LINK_RE);
    if (!m) { errors.push(`${slug}: not a 1262 ref link: ${ad.link}`); continue; }
    const id = m[1];
    const [w, h] = (ad.adName.match(/(\d+)x(\d+)\s*$/) || []).slice(1).map(Number);
    products[id] ||= {
      id,
      name: displayName(group),
      kind: kindOf(ad.target),
      href: ad.link,
      img: ad.img && !BROKEN_IMAGES.has(ad.img) ? ad.img : null,
      imgW: w || null,
      imgH: h || null
    };
    ids.push(id);
  }
  if (new Set(ids).size !== ids.length) errors.push(`${slug}: duplicate product`);
  const note = notes[slug] ? notes[slug](slug, exam?.name || slug) : null;
  exams[slug] = note ? { products: ids, note } : { products: ids };
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const body = `// AUTO-GENERATED by scripts/mometrix/build.mjs — do not edit by hand.
// Source: Mometrix affiliate panel (ID 1262) HTML Ads export + scripts/mometrix/exam-map.mjs.
//
// Every href is a Mometrix-issued tracking link (ref.mometrix.com/1262-…htm).
// Never rewrite or append parameters to them: they are untested in that form.

export const mometrixProducts = ${JSON.stringify(sorted(products), null, 2)};

export const mometrixExams = ${JSON.stringify(sorted(exams), null, 2)};

/** Products (featured first) and an optional caveat for an exam slug, or null. */
export function mometrixFor(slug) {
  const entry = mometrixExams[slug];
  if (!entry || !entry.products.length) return null;
  return { products: entry.products.map((id) => mometrixProducts[id]), note: entry.note || null };
}
`;
fs.writeFileSync(path.join(root, 'src/data/mometrix.mjs'), body);
console.log(`mometrix: ${Object.keys(exams).length} exams, ${Object.keys(products).length} products -> src/data/mometrix.mjs`);
